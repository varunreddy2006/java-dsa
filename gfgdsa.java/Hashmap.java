import java.util.*;

public class Hashmap{
    public static void main(String[] args){
        HashMap<String,Integer> map= new HashMap<>();

        map.put("varun",100);
        map.put("reddy",34);

        System.out.println(map.get("varun"));
        System.out.println(map.get("reddy"));
    }
}
